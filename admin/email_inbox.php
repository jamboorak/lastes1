        <div class="stats">
            <div class="stat-card">
                <div class="stat-number"><?php echo count($files); ?></div>
                <div class="stat-label">Total Emails</div>
            </div>
            <div class="stat-card">
                <div class="stat-number"><?php echo count(array_filter($files, function($f) { return strpos($f, 'approval') !== false; })); ?></div>
                <div class="stat-label">Approvals</div>
            </div>
            <div class="stat-card">
                <div class="stat-number"><?php echo count(array_filter($files, function($f) { return strpos($f, 'cancellation') !== false; })); ?></div>
                <div class="stat-label">Cancellations</div>
            </div>
        </div>
        
        <div class="email-list">
            <?php foreach ($files as $file): 
                $filePath = $emailDir . '/' . $file;
                $isApproval = strpos($file, 'approval') !== false;
                $type = $isApproval ? 'approval' : 'cancellation';
                $typeLabel = $isApproval ? 'APPROVAL' : 'CANCELLATION';
                $fileTime = filemtime($filePath);
                $fileDate = date('M d, Y H:i:s', $fileTime);
                $reservationId = preg_match('/_(\\d+)_/', $file, $m) ? $m[1] : '?';
            ?>
                <div class="email-item" onclick="viewEmail('<?php echo htmlspecialchars($file); ?>')">
                    <div class="email-info">
                        <div>
                            <span class="email-type <?php echo $type; ?>"><?php echo $typeLabel; ?></span>
                            <strong>Reservation #<?php echo $reservationId; ?></strong>
                        </div>
                        <div class="email-time"><?php echo $fileDate; ?></div>
                    </div>
                    <div class="email-actions">
                        <button class="btn btn-view" onclick="viewEmail('<?php echo htmlspecialchars($file); ?>'); return false;">View</button>
                        <button class="btn btn-delete" onclick="deleteEmail('<?php echo htmlspecialchars($file); ?>'); return false;">Delete</button>
                    </div>
                </div>
            <?php endforeach; ?>
