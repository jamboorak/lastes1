    <script>
        function viewEmail(filename) {
            fetch('email_view.php?file=' + encodeURIComponent(filename))
                .then(r => r.text())
                .then(content => {
                    document.getElementById('previewBody').innerHTML = content;
                    document.getElementById('emailPreview').classList.add('show');
                });
        }
        
        function closePreview() {
            document.getElementById('emailPreview').classList.remove('show');
        }
        
        function deleteEmail(filename) {
            if (confirm('Delete this email?')) {
                fetch('email_delete.php?file=' + encodeURIComponent(filename))
                    .then(r => r.json())
                    .then(data => {
                        if (data.success) {
                            location.reload();
                        } else {
                            alert('Error deleting email');
                        }
                    });
            }
        }
    </script>
